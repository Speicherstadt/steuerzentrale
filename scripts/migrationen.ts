/**
 * Writes apps/zentrale/src/db/migrationen.gen.ts from the migrations drizzle-kit generated, with
 * the SQL as strings, so `bun build --compile` embeds them in the binary. Run by
 * `bun run db:generate`; scripts/migrationen.test.ts fails when the file is out of date.
 * From Speicherstadt/soll, scripts/migrationen.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Journal = { entries: { idx: number; tag: string }[] };

export const migrationenQuelle = (ordner: string): string => {
  const journal = JSON.parse(readFileSync(join(ordner, "meta/_journal.json"), "utf8")) as Journal;
  const eintraege = [...journal.entries]
    .sort((a, b) => a.idx - b.idx)
    .map(({ tag }) => ({ tag, sql: readFileSync(join(ordner, `${tag}.sql`), "utf8") }));
  return `// Generated by scripts/migrationen.ts from apps/zentrale/drizzle; do not edit.
export const migrationen: readonly { tag: string; sql: string }[] = ${JSON.stringify(eintraege, null, 2)};
`;
};

export const ZIEL = "apps/zentrale/src/db/migrationen.gen.ts";
export const ORDNER = "apps/zentrale/drizzle";

if (import.meta.main) writeFileSync(ZIEL, migrationenQuelle(ORDNER));
